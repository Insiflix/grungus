const { app, BrowserWindow } = require("electron");
const fs = require("node:fs/promises");
const path = require("node:path");
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: false, width: 1280, height: 860, webPreferences: { backgroundThrottling: false, offscreen: true } });
  const evaluate = code => window.webContents.executeJavaScript(code);
  const waitFor = async code => { for (let i = 0; i < 150; i++) { if (await evaluate(code)) return; await new Promise(resolve => setTimeout(resolve, 100)); } throw new Error(`Timed out: ${code}`); };
  const screenshot = async name => { window.webContents.invalidate(); await evaluate('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))'); await new Promise(resolve => setTimeout(resolve, 250)); const image = await window.webContents.capturePage(); await fs.writeFile(path.join(app.getPath("temp"), `grungus-${name}.png`), image.toPNG()); };
  try {
    await window.loadURL(process.argv[2]);
    await waitFor('!!document.querySelector(".conversation-call")');
    await evaluate(`(() => { const sidebar = document.querySelector('.room-sidebar'); if (sidebar.textContent.includes('Lounge') || !sidebar.textContent.includes('Weekend crew') || !sidebar.textContent.includes('Group chats')) throw new Error('Group chats must be separate from server channels'); const tabs = document.querySelector('.dm-tabs').getBoundingClientRect(); const chat = document.querySelector('.chat-workspace').getBoundingClientRect(); if (chat.top - tabs.bottom > 4) throw new Error('DM gap is too large'); })()`);
    await evaluate(`(() => { const sidebar = document.querySelector('.room-sidebar').getBoundingClientRect(); const tabs = document.querySelector('.dm-tabs').getBoundingClientRect(); if (Math.abs(sidebar.top - tabs.top) > 1) throw new Error('Sidebar does not reach the top'); const row = document.querySelector('.room-row.is-selected'); if (row.getBoundingClientRect().height > 44) throw new Error('Chat rows are too tall'); if (getComputedStyle(row).boxShadow !== 'none') throw new Error('Selected row has a stripe'); if (document.querySelector('.dm-tabs__tools')) throw new Error('Redundant top tools remain'); })()`);
    await evaluate(`document.querySelector('.dm-tabs .dm-tab[aria-label^="Alice,"]').click()`);
    await waitFor('!!document.querySelector(".conversation-surface.has-connected-tab")');
    await evaluate('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))');
    await evaluate("window.navigationFixture.populateDm()");
    await waitFor('document.querySelectorAll(".timeline .message-row").length === 40');
    await evaluate(`(async () => {
      const frame = () => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
      const timeline = () => document.querySelector(".timeline");
      const atBottom = () => timeline().scrollHeight - timeline().scrollTop - timeline().clientHeight < 2;
      await frame();
      if (!atBottom()) throw new Error("Asynchronous DM history did not open at the bottom");
      timeline().scrollTop = 0;
      timeline().dispatchEvent(new Event("scroll"));
      await frame();
      if (timeline().scrollTop !== 0) throw new Error("Timeline prevented reading older messages");
      document.querySelector('.dm-tab[aria-label^="Bob,"]').click();
      await frame();
      document.querySelector('.dm-tab[aria-label^="Alice,"]').click();
      await frame();
      if (!atBottom()) throw new Error("Reopened DM did not reset to latest");
      const media = document.createElement("div");
      media.style.height = "1800px";
      timeline().querySelector(".timeline__inner").append(media);
      // Reproduce layout scroll delivery before ResizeObserver.
      timeline().dispatchEvent(new Event("scroll"));
      await frame();
      if (!atBottom()) throw new Error("Delayed media released the bottom pin");
      media.remove();
      await frame();
    })()`);
    const switchingFrames = await evaluate(`(async () => {
      const surface = document.querySelector('.conversation-surface');
      const pane = surface.querySelector('.conversation-surface__pane-glass');
      const times = [];
      for (let index = 0; index < 8; index++) {
        const before = performance.now();
        const previous = surface.querySelector('.conversation-surface__outline path').getAttribute('d');
        const tabs = surface.querySelectorAll('.dm-tab');
        tabs[index % 2 === 0 ? 1 : 0].click();
        await new Promise(resolve => requestAnimationFrame(resolve));
        if (surface.querySelector('.conversation-surface__outline path').getAttribute('d') === previous) throw new Error('Tab shape lagged behind the chat switch');
        if (surface.querySelector('.conversation-surface__pane-glass') !== pane) throw new Error('Chat backdrop was recreated on tab switch');
        times.push(performance.now() - before);
      }
      return times;
    })()`);
    console.log(JSON.stringify({ tabSwitchFirstFrameMs: switchingFrames }));
    await screenshot("connected-dm");
    await evaluate('document.documentElement.dataset.theme = "light"');
    await screenshot("connected-dm-light");
    await evaluate('document.documentElement.dataset.theme = "dark"');
    await screenshot("connected-dm-dark");
    await evaluate('delete document.documentElement.dataset.theme');
    await evaluate(`[...document.querySelectorAll('.room-row')].find(row => row.textContent.includes('Weekend crew')).click()`);
    await evaluate(`document.querySelector('[aria-label="Close channel general"]').click()`);
    await waitFor("!document.querySelector('[aria-label=\"Close channel general\"]')");
    await evaluate(`document.querySelector('[aria-label="The Forest"]').click()`);
    await waitFor("!!document.querySelector('[aria-label=\"Close channel general\"]')");
    await waitFor('!!document.querySelector(".conversation-surface.has-connected-tab")');
    await screenshot("connected-channel");
    await evaluate(`document.querySelector('[aria-label="Close channel general"]').click()`);
    await waitFor("!document.querySelector('[aria-label=\"Close channel general\"]')");
    await evaluate('window.navigationFixture.incomingChannelMessage()');
    await waitFor("!!document.querySelector('[aria-label=\"Close channel general\"]')");
    await evaluate(`document.querySelector('[aria-label="Grungus home"]').click()`);
    await waitFor('!!document.querySelector(".grungus-home")');
    await evaluate(`if (!document.querySelector('.home-header button')?.textContent.includes('Add people') || document.querySelector('.home-header').textContent.includes('all in one place')) throw new Error('Dashboard cleanup missing')`);
    await screenshot("home");
    await evaluate(`[...document.querySelectorAll('.room-row')].find(row => row.textContent.includes('Weekend crew')).click()`);
    await waitFor('!!document.querySelector(".composer")');
    await evaluate(`document.querySelector('[aria-label="Add attachment or poll"]').click()`);
    await evaluate(`[...document.querySelectorAll('.composer-add-menu button')].find(button => button.textContent === 'Create poll').click()`);
    await waitFor('!!document.querySelector(".poll-dialog[open]")');
    await evaluate(`(() => { const fields = document.querySelectorAll('.poll-dialog input:not([type="checkbox"]):not([type="number"])'); ['Lunch?', 'Pizza', 'Pasta'].forEach((value, index) => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(fields[index], value); fields[index].dispatchEvent(new Event('input', { bubbles: true })); }); })()`);
    await evaluate(`(() => { const rect = document.querySelector(".poll-dialog").getBoundingClientRect(); if (Math.abs(rect.left + rect.width / 2 - innerWidth / 2) > 2 || Math.abs(rect.top + rect.height / 2 - innerHeight / 2) > 2) throw new Error("Poll editor must be centered"); })()`);
    await screenshot("poll-editor");
    await evaluate(`document.querySelector('.poll-dialog form').requestSubmit()`);
    await waitFor('!!document.querySelector(".poll-message")');
    await evaluate(`document.querySelector('.poll-option input').click()`);
    await evaluate(`[...document.querySelectorAll('.poll-message footer button')].find(button => button.textContent === 'Vote').click()`);
    await waitFor('document.querySelector(".poll-message").textContent.includes("1 voter")');
    await screenshot("poll-results");
    await evaluate(`[...document.querySelectorAll('.poll-message footer button')].find(button => button.textContent === 'End poll').click()`);
    await waitFor('document.querySelector(".poll-caption").textContent.includes("Poll ended")');
    await screenshot("groups");
    await evaluate(`document.querySelector('[aria-label="Create server"]').click()`);
    await waitFor('!!document.querySelector(\'dialog[aria-label="Create server"][open]\')');
    await screenshot("create-server");
    await evaluate(`(() => { const dialog = document.querySelector('dialog[aria-label="Create server"]'); const input = dialog.querySelector('input'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, 'My server'); input.dispatchEvent(new Event('input', { bubbles: true })); })()`);
    await evaluate(`document.querySelector('dialog[aria-label="Create server"] form').requestSubmit()`);
    await waitFor('document.querySelector(".sidebar-header strong")?.textContent === "My server"');
    await evaluate(`if (!document.querySelector('[aria-label="My server"][aria-pressed="true"]')) throw new Error('Created server was not selected')`);
    await evaluate(`document.querySelector('[aria-label="The Forest"]').click()`);
    await waitFor('!!document.querySelector(\'[aria-label="Open text channel introductions"]\')');
    await evaluate(`(() => { const create = document.querySelector('[aria-label="Create channel"]'); const sidebar = document.querySelector('.room-sidebar').getBoundingClientRect(); if (create.getBoundingClientRect().right > sidebar.right) throw new Error('Create channel button is clipped'); create.click(); })()`);
    await waitFor('!!document.querySelector(".create-channel-dialog[open]")');
    await evaluate(`(() => { const rect = document.querySelector('.create-channel-dialog').getBoundingClientRect(); if (Math.abs(rect.left + rect.width / 2 - innerWidth / 2) > 2 || Math.abs(rect.top + rect.height / 2 - innerHeight / 2) > 2) throw new Error('Create channel dialog must be centered'); })()`);
    await screenshot("create-channel");
    await evaluate(`document.querySelector('[aria-label="Close create channel"]').click()`);
    await evaluate(`(() => { const sidebar = document.querySelector('.room-sidebar'); if (sidebar.textContent.includes('Weekend crew')) throw new Error('Group chats leaked into the server'); const members = sidebar.querySelector('.voice-members'); if (!members?.textContent.includes('Alice') || !members.textContent.includes('Bob')) throw new Error('Voice participants missing'); document.querySelector('[aria-label="Open text channel introductions"]').click(); })()`);
    await waitFor('document.querySelector(".room-header h1")?.textContent === "introductions"');
    await screenshot("server");
    await evaluate(`document.querySelector('[aria-label="Join voice channel Lounge"]').click()`);
    await waitFor('!!document.querySelector(".call-panel--voice")');
    await waitFor('!!document.querySelector(".call-panel--voice .voice-channel-chat textarea")');
    await evaluate(`(() => { const chat = document.querySelector('.call-panel--voice .voice-channel-chat'); const input = chat.querySelector('textarea'); Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set.call(input, 'Hello from voice'); input.dispatchEvent(new Event('input', { bubbles: true })); })()`);
    await evaluate(`document.querySelector('.call-panel--voice .voice-channel-chat form').requestSubmit()`);
    await waitFor('document.querySelector(".call-panel--voice .voice-channel-chat .message-body-text")?.textContent.includes("Hello from voice")');
    await screenshot("voice-call-chat");
    await evaluate(`document.querySelector('.call-hangup').click()`);
    await waitFor('!document.querySelector(".call-panel") && !!document.querySelector(".conversation-call--voice")');
    await screenshot("voice");
    await evaluate(`document.querySelector('[aria-label="Grungus home"]').click()`);
    await waitFor('!!document.querySelector(".grungus-home")');
    await evaluate(`[...document.querySelectorAll('.room-row')].find(row => row.textContent.includes('Weekend crew')).click()`);
    await waitFor('!!document.querySelector(".conversation-call:not(.conversation-call--voice)")');
    await evaluate(`document.querySelector('.conversation-call__actions button').click()`);
    await waitFor('!!document.querySelector(".call-panel--group")');
    await screenshot("group-call");
    await evaluate(`document.querySelector('.call-hangup').click()`);
    window.setSize(760, 700);
    await screenshot("groups-narrow");
    console.log(JSON.stringify({ passed: true, checks: ["DM initial/reopen/delayed-media bottom positioning", "manual history scrolling", "compact DM gap", "full-height sidebar", "compact chat rows", "channel tab hide/reopen/new message", "dashboard cleanup", "create/vote/end poll", "separate group chats", "create and open server", "public channel discovery and join", "voice participants", "send text during voice call", "voice channel view", "group call view"], screenshots: path.join(app.getPath("temp"), "grungus-*.png") }));
    app.exit(0);
  } catch (error) { console.error(error); app.exit(1); }
});
