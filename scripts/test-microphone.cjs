const { app, BrowserWindow } = require('electron');
app.commandLine.appendSwitch('use-fake-device-for-media-stream');
app.commandLine.appendSwitch('use-fake-ui-for-media-stream');
app.commandLine.appendSwitch('autoplay-policy', 'no-user-gesture-required');
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width:1100, height:1500, webPreferences: { offscreen: true, sandbox: true, contextIsolation: true, backgroundThrottling: false } });
  win.webContents.setAudioMuted(true);
  const errors = [];
  win.webContents.on('console-message', event => { if (event.level === 'error' || /Content Security Policy/.test(event.message)) errors.push(event.message); });
  const timer = setTimeout(() => { console.error('Audio smoke test timed out'); app.exit(1); }, 45000);
  try {
    await win.loadURL(process.argv[2]);
    const result = await win.webContents.executeJavaScript(`(async () => {
      const assert = (condition, message) => { if (!condition) throw new Error(message); };
      const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
      const warnings = []; window.addEventListener('grungus:audio-warning', event => warnings.push(event.detail));
      const sourceContext = new AudioContext({ sampleRate:48000 }); await sourceContext.resume();
      const oscillator = sourceContext.createOscillator(); oscillator.frequency.value = 440;
      const volume = sourceContext.createGain(); volume.gain.value = .1;
      const sink = sourceContext.createMediaStreamDestination(); oscillator.connect(volume).connect(sink); oscillator.start();
      const native = sink.stream.getAudioTracks()[0];
      native.applyConstraints = async () => {}; // Web Audio-generated tracks have no physical capture capabilities.
      let requested, synthetic = true;
      const realCapture = navigator.mediaDevices.getUserMedia.bind(navigator.mediaDevices);
      navigator.mediaDevices.getUserMedia = async constraints => { requested = constraints; if (synthetic) return new MediaStream([native]); const value = await realCapture(constraints); window.__nativeTestTrack = value.getAudioTracks()[0]; return value; };
      await new Promise((resolve,reject) => { const script = document.createElement('script'); script.src='/audio/microphone-processing.js'; script.onload=resolve; script.onerror=reject; document.head.append(script); });
      const stream = await navigator.mediaDevices.getUserMedia({ audio:true });
      assert(requested.audio.echoCancellation && requested.audio.noiseSuppression && requested.audio.autoGainControl, 'Speech defaults not applied');
      assert(stream.getAudioTracks()[0] !== native, 'Raw microphone published');
      const analyser = sourceContext.createAnalyser(); analyser.fftSize=2048;
      sourceContext.createMediaStreamSource(stream).connect(analyser);
      const rms = async () => { await pause(300); const data=new Float32Array(analyser.fftSize); analyser.getFloatTimeDomainData(data); return Math.sqrt(data.reduce((sum,x)=>sum+x*x,0)/data.length); };
      const normal = await rms(); assert(normal > .01, 'Output is silent: '+normal);
      await window.grungusAudio.configure({ inputGain:0 }); const muted = await rms(); assert(muted < .0001, 'Gain does not control outgoing audio: '+muted);
      await window.grungusAudio.configure({ inputGain:100, advancedNoiseSuppression:true }); await pause(500);
      assert(warnings.length===0, 'RNNoise fallback: '+warnings.join(', '));
      await window.grungusAudio.configure({ advancedNoiseSuppression:false });
      assert(await rms() > .01, 'RNNoise bypass did not restore audio');
      const clone = stream.clone(); stream.getTracks().forEach(track=>track.stop());
      assert(native.readyState === 'live', 'Stopping one stream killed its clone');
      clone.getTracks().forEach(track=>track.stop());
      assert(native.readyState === 'ended', 'Last clone leaked the native microphone');
      oscillator.stop(); await sourceContext.close();
      synthetic = false;
      const hardware = await navigator.mediaDevices.getUserMedia({ audio:true });
      const settings = hardware.getAudioTracks()[0].getSettings();
      assert(settings.echoCancellation === true && settings.autoGainControl === true, 'Native capture settings missing: '+JSON.stringify(settings));
      await window.grungusAudio.configure({ advancedNoiseSuppression:true });
      await pause(500);
      assert(warnings.length===0, 'Native RNNoise processing failed: '+warnings.join(', '));
      hardware.getTracks().forEach(track => track.stop());
      return { normal, muted, rnnoise:true, cloneCleanup:true };
    })().catch(error => ({ error: { name:error.name, message:error.message, stack:error.stack, constraint:error.constraint } }))`);
    if (result.error) throw new Error(JSON.stringify(result.error));
    if (errors.length) throw new Error(errors.join('\n'));
    const waitFor = async code => { for (let i=0;i<100;i++) { if (await win.webContents.executeJavaScript(code)) return; await new Promise(resolve => setTimeout(resolve, 50)); } throw new Error('UI timed out: '+code); };
    const click = text => win.webContents.executeJavaScript(`[...document.querySelectorAll('button')].find(button => button.textContent === ${JSON.stringify(text)}).click()`);
    await waitFor("[...document.querySelectorAll('button')].some(button => button.textContent === 'Start microphone test')");
    await win.webContents.executeJavaScript("window.grungusAudio.configure({advancedNoiseSuppression:false,inputGain:100})");
    await click('Start microphone test');
    await waitFor("document.querySelector('audio')?.srcObject && [...document.querySelectorAll('button')].some(button => button.textContent === 'Stop microphone test')");
    await win.webContents.executeJavaScript("if(document.querySelector('audio').muted) throw new Error('Mirror is muted')");
    await click('Record 10-second sample');
    await waitFor("document.querySelector('audio').muted");
    await new Promise(resolve => setTimeout(resolve, 500));
    await click('Finish recording');
    await waitFor("document.querySelector('audio[controls]')?.src.startsWith('blob:')");
    await win.webContents.executeJavaScript("document.querySelector('audio[controls]').play()");
    await waitFor("document.querySelector('audio[controls]').currentTime > 0 && !document.querySelector('audio[controls]').error");
    await win.webContents.executeJavaScript("document.querySelector('audio[controls]').pause()");
    await click('Stop microphone test');
    await waitFor("window.__nativeTestTrack.readyState === 'ended' && !document.querySelector('audio').srcObject");
    require('node:fs').mkdirSync('artifacts', {recursive:true});
    require('node:fs').writeFileSync('artifacts/microphone-settings.png', (await win.webContents.capturePage()).toPNG());
    console.log('PASS: settings microphone mirror, recording playback and Stop release the native input.');
    console.log('PASS: real Web Audio output, live gain, local RNNoise worklet/WASM, bypass, clone cleanup and CSP.', result);
    clearTimeout(timer); win.destroy(); app.exit(0);
  } catch (error) { console.error(error?.stack || error?.message || JSON.stringify(error)); clearTimeout(timer); app.exit(1); }
});

